-- Dieselbe Regel wie tier2Treffer() in pipeline-simple.ts, fuer den Nachlauf.
create or replace function signal_layer.tier2_treffer(p_company text, p_text text)
returns text[]
language sql stable
set search_path = signal_layer, pg_temp
as $$
  select coalesce(array_agg(t.name order by t.name), '{}')
  from signal_layer.tier2_companies t
  where t.active and exists (
    select 1 from unnest(array[t.name] || t.aliases) n
    where (coalesce(p_company,'') ~ ('(^|[^[:alnum:]])' || regexp_replace(n, '([.*+?^${}()|\[\]\\])', '\\\1', 'g') || '($|[^[:alnum:]])'))
       or (not t.nur_firma and coalesce(p_text,'') ~ ('(^|[^[:alnum:]])' || regexp_replace(n, '([.*+?^${}()|\[\]\\])', '\\\1', 'g') || '($|[^[:alnum:]])'))
  );
$$;

